#!/usr/bin/env python3
"""Generate src/language/python-names.ts: the exact names Python guessit prints.

Python guessit's JSON encoder writes babelfish `.name` for languages and
countries ("French", "UNITED STATES"). guessit-js's default output is that same
notation, so the names come from babelfish itself rather than a hand-kept list.

Run with a Python that has guessit (and so babelfish) installed:
    python scripts/python-names.py
"""

import json
import re
from pathlib import Path

import babelfish

root = Path(__file__).resolve().parent.parent
data = (root / "src" / "language" / "data.ts").read_text()
codes = sorted(set(re.findall(r"alpha3: '([a-z]{3})'", data)) | {"mul", "und"})

languages, missing = {}, []
for code in codes:
    lang = None
    for make in (babelfish.Language, babelfish.Language.fromalpha3b):
        try:
            lang = make(code)
            break
        except Exception:
            continue
    if lang is None:
        missing.append(code)
        continue
    languages[code] = lang.name

countries = {code: babelfish.Country(code).name for code in sorted(babelfish.COUNTRIES)}

out = [
    "// Generated by scripts/python-names.py from babelfish "
    f"{getattr(babelfish, '__version__', '')}. Do not edit by hand.",
    "// The names Python guessit's JSON encoder prints for languages and countries.",
    "",
    "export const PYTHON_LANGUAGE_NAMES: Record<string, string> = "
    + json.dumps(languages, ensure_ascii=False, indent=2) + ";",
    "",
    "export const PYTHON_COUNTRY_NAMES: Record<string, string> = "
    + json.dumps(countries, ensure_ascii=False, indent=2) + ";",
    "",
]
target = root / "src" / "language" / "python-names.ts"
target.write_text("\n".join(out))
print(f"✓ {target.relative_to(root)}: {len(languages)} languages, {len(countries)} countries")
if missing:
    print("  not in babelfish (kept as code):", ", ".join(missing))
